package io.fireflysoftware.experience.onboarding.web.controllers;

import io.fireflysoftware.experience.onboarding.core.ports.AccessDeniedException;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestControllerAdvice;

import java.util.Map;

@RestControllerAdvice
public class OnboardingAccessDeniedHandler {

    @ExceptionHandler(AccessDeniedException.class)
    @ResponseStatus(HttpStatus.FORBIDDEN)
    public Map<String, String> denied(AccessDeniedException exception) {
        return Map.of("reason", exception.getMessage());
    }
}
